H.buffer({ "\tA", "12345678B" }, { 1, 0 })
vim.bo.tabstop = 8
vim.o.virtualedit = "block"
-- Start inside the tab, then select four display cells, matching native block yank.
vim.fn.setpos(".", { 0, 1, 1, 0 })
H.keys("<C-v>3lj")
local block = require("editing_tools.range").visual()
local source = require("editing_tools.range").get(block)
H.keys("gm")
local expected = {}
for i, segment in ipairs(block.segments) do
  local line = ({ "\tA", "12345678B" })[i]
  expected[i] = line:sub(1, segment.start)
    .. segment.prefix
    .. source[i]:rep(2)
    .. segment.suffix
    .. line:sub(segment.finish + 1)
end
H.eq(H.lines(), expected, "partial-tab block agrees with native region")
vim.o.virtualedit = ""

